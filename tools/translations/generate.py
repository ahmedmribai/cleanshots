"""Builds app/src/main/res/values-<lang>/strings.xml from the translation tables.

Run from the repo root: python tools/translations/generate.py
Fails if a language is missing a key or a placeholder differs from English.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "app", "src", "main", "res")
sys.path.insert(0, HERE)

from translations_a import T as TA  # noqa: E402
from translations_b import T as TB  # noqa: E402

# Newer CLDR rules give these languages a "many" form (used for very large numbers).
NEEDS_MANY = {"es", "fr", "it", "pt-rBR"}
# Android resolves Indonesian from the legacy "in" code.
FOLDER = {"id": "in"}
PLACEHOLDER = re.compile(r"%(?:\d+\$)?[sd]|%%")


def load_base():
    root = ET.parse(os.path.join(RES, "values", "strings.xml")).getroot()
    strings, plurals = {}, {}
    for el in root:
        if el.get("translatable") == "false":
            continue
        if el.tag == "string":
            strings[el.get("name")] = el.text
        elif el.tag == "plurals":
            plurals[el.get("name")] = {i.get("quantity"): i.text for i in el}
    return strings, plurals


def escape(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')


def placeholders(text):
    return sorted(p for p in PLACEHOLDER.findall(text) if p != "%%")


def check(lang, base_s, base_p, data):
    errors = []
    for key, en in base_s.items():
        tr = data["strings"].get(key)
        if tr is None:
            errors.append(f"{lang}: missing string {key}")
        elif placeholders(tr) != placeholders(en):
            errors.append(f"{lang}: placeholder mismatch in {key}: {tr!r}")
    for key in data["strings"]:
        if key not in base_s:
            errors.append(f"{lang}: unknown string {key}")
    for key, forms in base_p.items():
        tr = data["plurals"].get(key)
        if tr is None:
            errors.append(f"{lang}: missing plural {key}")
            continue
        expected = placeholders(forms["other"])
        for q, text in tr.items():
            if placeholders(text) != expected:
                errors.append(f"{lang}: placeholder mismatch in {key}/{q}: {text!r}")
    return errors


def write(lang, base_s, base_p, data):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/translations/generate.py. Do not edit by hand. -->", "<resources>"]
    for key in base_s:
        lines.append(f'    <string name="{key}">{escape(data["strings"][key])}</string>')
    for key in base_p:
        forms = dict(data["plurals"][key])
        if lang in NEEDS_MANY and "many" not in forms:
            forms["many"] = forms["other"]
        lines.append(f'    <plurals name="{key}">')
        for q in ("zero", "one", "two", "few", "many", "other"):
            if q in forms:
                lines.append(f'        <item quantity="{q}">{escape(forms[q])}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    out_dir = os.path.join(RES, f"values-{FOLDER.get(lang, lang)}")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    base_s, base_p = load_base()
    tables = {**TA, **TB}
    errors = [e for lang, data in tables.items() for e in check(lang, base_s, base_p, data)]
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    for lang, data in tables.items():
        write(lang, base_s, base_p, data)
    print(f"Wrote {len(tables)} languages: {', '.join(sorted(tables))}")


if __name__ == "__main__":
    main()
